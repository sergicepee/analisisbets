export function translate(lang: LangCode, es: string): string {
  if (lang !== "en") return es;
  if (es.startsWith("Más de ") || es.includes(": más de ")) {
    return es.replace("Más de ", "Over ").replace(": más de ", ": over ")
      .replace(" goles", " goals").replace(" córners", " corners").replace(" tarjetas", " cards").replace(" TAP", " shots on target");
  }
  if (es.startsWith("Menos de ")) {
    return es.replace("Menos de ", "Under ").replace(" goles", " goals").replace(" córners", " corners").replace(" tarjetas", " cards").replace(" TAP", " shots on target");
  }
  if (es.endsWith(" gana")) return `${es.slice(0, es.length - " gana".length)} wins`;
  if (es.startsWith("Ambos marcan · ")) return es.replace("Ambos marcan · ", "Both teams to score · ").replace("Sí", "Yes");
  if (es.startsWith("Promedio de ")) return `Average ${es.slice("Promedio de ".length)}`;
  if (es.startsWith("Jornada ")) return `Matchday ${es.slice("Jornada ".length)}`;
  if (es.startsWith("Partidos con gol: ")) return `Matches with a goal: ${es.slice("Partidos con gol: ".length)}`;
  if (es.startsWith("Muestra: ")) return `Sample: ${es.slice("Muestra: ".length)}`;
  if (es.startsWith("Resultado final: ")) return `Final score: ${es.slice("Resultado final: ".length)}`;
  if (es.startsWith("Consejo de API-Football: ")) return `API-Football advice: ${es.slice("Consejo de API-Football: ".length)}`;
  if (es.startsWith("Goles estimados con la media de los últimos ")) return es.replace("Goles estimados con la media de los últimos ", "Goals estimated from each team's last ").replace(" partidos de cada equipo según API-Football (no hay estadísticas propias disponibles).", " matches according to API-Football (no in-house stats are available).");
  return EN[es] ?? es;
}
